    сохранить('документы/акты_определения_уз.txt','\n\n'.join(акты))
    for с in системы:
        меры[с['номер']]=подобрать_меры(с,расчёты[с['номер']],каталог)
    план=[]
    for с in системы:
        for м in меры[с['номер']]['пробелы']:
            план.append(f'{с["номер"]}: {м["код"]} {м["название"]}; действие — настроить и испытать; ответственный — {с["ответственный"]}; подтверждение — {м["способ_проверки"]}')
