"""Запуск: python программы/главный_симулятор.py [все|система НОМЕР|сценарий НОМЕР|тесты]."""
import sys as система_питон
import json as обмен
from pathlib import Path
from copy import deepcopy as копия
from datetime import datetime as ДатаВремя, timedelta as Интервал
КОРЕНЬ=Path(__file__).resolve().parents[1]
система_питон.path.insert(0,str(КОРЕНЬ))
from программы.документы import дата_сейчас, сохранить_документ, текст_акта

def загрузить():
    from importlib import import_module as импорт
    обязательные={'организация':'организация','системы':'системы','матрица_уз':'матрица','каталог_мер':'каталог_мер',
      'оборудование':'оборудование','справочник_сзи':'средства','тестовые_сценарии':'сценарии'}
    результат={}
    for файл,поле in обязательные.items():
        if not (КОРЕНЬ/'данные'/f'{файл}.py').is_file():
            raise ValueError(f'Отсутствует обязательный файл данные/{файл}.py, поле {поле}')
        модуль=импорт('данные.'+файл)
        if not hasattr(модуль,поле):
            raise ValueError(f'данные/{файл}.py: отсутствует поле {поле}')
        значение=getattr(модуль,поле)
        if not isinstance(значение,dict if файл=='организация' else list):
            raise ValueError(f'данные/{файл}.py: неверный тип поля {поле}')
        результат[поле]=копия(значение)
    return результат

def сохранить(путь,текст):
    (КОРЕНЬ/путь).write_text(текст+'\n',encoding='utf-8')

def показать_сценарий(номер,данные):
    from программы.расчёт_уз import рассчитать_уз, строгий_уровень
    сценарий=next((с for с in данные['сценарии'] if str(с['номер'])==str(номер)),None)
    if сценарий is None:
        raise ValueError('Номер сценария должен быть от 1 до 6')
    результаты=[рассчитать_уз(*в) for в in сценарий['входы']]
    текст=f'Сценарий {номер}: {сценарий["название"]}\n'+ '\n'.join(обмен.dumps(р,ensure_ascii=False,indent=2) for р in результаты)
    текст+='\nОбщий уровень: '+строгий_уровень(результаты)+'. Для общей инфраструктуры выбирается минимальный номер УЗ.'
    if str(номер)=='6': текст+=' В сценарии 6 оба контура дают УЗ-3.'
    сохранить(f'отчёты/сценарий_{номер}.txt',текст)
    return текст

def сформировать(данные):
    from программы.проверка_исходных_данных import проверить_вход
