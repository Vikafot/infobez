def импорт_акта(части,данные):
    from программы.расчёт_уз import уровень_системы
    if len(части)<3:
        raise ValueError('Не хватает номера ИСПДн: сценарий импорт КД (или КЛ, МД). Также: сценарий импорт путь.json')
    цель=части[2]
    система=next((с for с in данные['системы'] if с['номер']==цель),None)
    if система is None:
        путь=Path(' '.join(части[2:]).strip('"'))
        if not путь.exists():
            raise ValueError('Не найдена система или JSON-файл импорта: '+str(путь))
        система=обмен.loads(путь.read_text(encoding='utf-8-sig'))
        поля=('номер','название','границы_системы','категория_пдн','примеры_данных','тип_субъектов','количество_субъектов','тип_угроз_по_условию','является_гис')
        нет=[п for п in поля if п not in система]
        if нет: raise ValueError('Импорт: отсутствуют поля '+', '.join(нет))
    расчёт=уровень_системы(система)
    if расчёт['ошибки_ввода']: raise ValueError('; '.join(расчёт['ошибки_ввода']))
    # Идентификатор из JSON никогда не используется как файловый путь.
    путь=КОРЕНЬ/'документы/акт_импорт.docx'
    сохранить_документ(путь,'АКТ ОПРЕДЕЛЕНИЯ УРОВНЯ ЗАЩИЩЁННОСТИ',текст_акта(данные['организация'],система,расчёт,дата_сейчас()))
    return 'Акт сформирован: '+str(путь)

def выполнить(команда):
    части=команда.strip().replace('“','').replace('”','').split()
    if not части: return 'Введите: все; система КД; сценарий 1; сценарий импорт КД; тесты; выход'
    if части[0]=='выход': return 'выход'
    данные=загрузить()
    if части[0]=='все':
        результат=сформировать(данные)
        for номер in range(1,7): показать_сценарий(номер,данные)
        return f'Проверено систем: {len(данные["системы"])}; дефектов: {len(результат["дефекты"])}; оценка {результат["оценка"]}/100. Отчёт: отчёты/итоговый_отчёт.txt'
    if части[0]=='система':
        if len(части)!=2: raise ValueError('Не хватает номера: система КД (или КЛ, МД)')
        if части[1] not in {с['номер'] for с in данные['системы']}: raise ValueError('Неизвестный номер ИСПДн')
        сформировать(данные)
        # Полный согласованный комплект обновлён; выборка сохраняется отдельно, не искажая общий паспорт.
        from программы.расчёт_уз import уровень_системы
        с=next(с for с in данные['системы'] if с['номер']==части[1])
        полный=обмен.loads((КОРЕНЬ/'отчёты/результат.json').read_text(encoding='utf-8'))
        выборка={'система':с,'расчёт':уровень_системы(с),'меры':полный['меры'][части[1]],
          'проверки':[п for п in полный['аудит']['проверки'] if '/' not in п['код'] or п['код'].endswith('/'+части[1])]}
        текст=обмен.dumps(выборка,ensure_ascii=False,indent=2)
        сохранить('отчёты/выбранная_система.txt',текст); return текст
    if части[0]=='сценарий':
        if len(части)<2: raise ValueError('Не хватает номера сценария (1–6) или слова импорт')
        if части[1].strip('"')=='импорт': return импорт_акта(части,данные)
        return показать_сценарий(части[1],данные)
    if части[0]=='тесты':
        from тесты.проверки import выполнить_тесты
        результаты=выполнить_тесты()
        неудачи=[р for р in результаты if not р['пройден']]
        if неудачи: raise ValueError('Не пройдены тесты: '+str(неудачи))
        return f'Пройдено тестов: {len(результаты)}. Таблица: отчёты/автоматические_тесты.txt'
    raise ValueError('Неизвестная команда. Доступны: все; система; сценарий; тесты; выход')

def безопасно(команда):
    try:
        return выполнить(команда)
    except Exception as ошибка:
        return 'Ошибка: '+str(ошибка)+' ['+type(ошибка).__name__+']. Проверьте указанный файл и поля исходных данных.'

if __name__=='__main__':
    if len(система_питон.argv)>1:
        ответ=безопасно(' '.join(система_питон.argv[1:])); print(ответ)
        if ответ.startswith('Ошибка:'): система_питон.exit(1)
    else:
        print('Симулятор ИСПДн. Команды: все; система КД/КЛ/МД; сценарий 1–6; сценарий импорт КД; тесты; выход')
        while True:
            try: команда=input('> ')
            except (EOFError,KeyboardInterrupt): break
            ответ=безопасно(команда)
            if ответ=='выход': break
            print(ответ)
