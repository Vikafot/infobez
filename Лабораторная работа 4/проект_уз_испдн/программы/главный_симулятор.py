    ошибки=проверить_вход(организация,системы,оборудование,каталог,средства)
    if ошибки:
        raise ValueError('\n'.join(f'{о["файл"]}, поле {о["поле"]}: {о["причина"]}' for о in ошибки))
    дата=дата_сейчас(); расчёты={}; меры={}; акты=[]
    реестр=[]
    for с in системы:
        номер=с['номер']; расчёты[номер]=уровень_системы(с)
        акт=текст_акта(организация,с,расчёты[номер],дата)
        акты.append('\n'.join(акт))
        сохранить_документ(КОРЕНЬ/'документы'/f'акт_{номер}.docx','АКТ ОПРЕДЕЛЕНИЯ УРОВНЯ ЗАЩИЩЁННОСТИ',акт)
        реестр.append(обмен.dumps(с,ensure_ascii=False,indent=2))
