from copy import deepcopy as копия
from данные.матрица_уз import матрица

def рассчитать_уз(категория, тип_субъектов, количество, тип_угроз):
    параметры = dict(категория=категория, тип_субъектов=тип_субъектов, количество=количество, тип_угроз=тип_угроз)
    ошибки = []
    if not isinstance(категория, str) or категория not in {п['категория'] for п in матрица}:
        ошибки.append('категория: требуется специальные / биометрические / общедоступные / иные')
    if not isinstance(тип_субъектов, str) or тип_субъектов not in ('сотрудники', 'не_сотрудники'):
        ошибки.append('тип_субъектов: требуется сотрудники или не_сотрудники')
    if type(количество) is not int or количество < 1:
        ошибки.append('количество: требуется положительное целое число, bool недопустим')
    if type(тип_угроз) is not int or тип_угроз not in (1, 2, 3):
        ошибки.append('тип_угроз: требуется заданное целое число 1, 2 или 3')
    результат = {'уровень':'недостаточно_данных','обоснование':'','проверенные_параметры':копия(параметры),
                 'основание_матрицы':None,'ошибки_ввода':ошибки}
    if ошибки:
        результат['обоснование'] = '; '.join(ошибки)
        return результат
    диапазон = 'до_100000_включительно' if количество <= 100000 else 'свыше_100000'
    правила = [п for п in матрица if (п['категория'],п['группа'],п['диапазон'],п['тип_угроз']) ==
               (категория,тип_субъектов,диапазон,тип_угроз)]
    if len(правила) != 1:
        результат['ошибки_ввода'] = ['матрица: правило отсутствует или неоднозначно']
        результат['обоснование'] = результат['ошибки_ввода'][0]
        return результат
    правило = правила[0]
    результат.update(уровень=правило['уровень'], основание_матрицы=правило['ключ'],
        обоснование=f'{категория}; {тип_субъектов}; {количество} субъектов ({диапазон}); задан тип угроз {тип_угроз}. Правило {правило["ключ"]}.')
    if количество == 100000:
        результат['обоснование'] += ' Ровно 100000: учебное допущение ≤100000; правовая граница требует отдельной проверки.'
    return результат

def уровень_системы(система):
    return рассчитать_уз(система.get('категория_пдн'), система.get('тип_субъектов'),
                        система.get('количество_субъектов'), система.get('тип_угроз_по_условию'))

def строгий_уровень(результаты):
    уровни = [р['уровень'] for р in результаты]
    if not уровни or 'недостаточно_данных' in уровни:
        return 'недостаточно_данных'
    return min(уровни, key=lambda у: int(у[-1]))
