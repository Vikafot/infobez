def проверить_оборудование(оборудование, системы):
    замечания=[]
    номера={с['номер'] for с in системы}
    известные={о['номер'] for о in оборудование}
    def добавить(элемент, поле, причина, действие):
        замечания.append({'оборудование':элемент.get('номер'), 'системы':элемент.get('связанная_испдн',[]),
                         'поле':поле,'причина':причина,'рекомендация':действие})
    for элемент in оборудование:
        связи=элемент.get('связанная_испдн')
        if not isinstance(связи,list) or not связи or any(с not in номера for с in связи):
            добавить(элемент,'связанная_испдн','Связь с ИСПДн отсутствует или ведёт к неизвестной системе','Указать существующие ИСПДн после инвентаризации')
        elif any(элемент['номер'] not in с.get('связанное_оборудование',[]) for с in системы if с['номер'] in связи):
            добавить(элемент,'обратная_ссылка','Оборудование связано с системой, но отсутствует в её перечне','Согласовать связь в обоих реестрах')
        if элемент.get('класс_по_учебной_схеме') not in ('ОТСС','ВТСС'):
            добавить(элемент,'класс_по_учебной_схеме','Не заполнена классификация ОТСС/ВТСС','Определить роль и заполнить классификацию')
        if type(элемент.get('обрабатывает_пдн')) is not bool or элемент.get('обрабатывает_пдн') != элемент.get('роль_требует_пдн'):
            добавить(элемент,'обрабатывает_пдн','Признак обработки противоречит структурированному описанию роли','Согласовать роль и признак обработки ПДн')
        if элемент.get('обрабатывает_пдн') and элемент.get('класс_по_учебной_схеме') == 'ВТСС':
            добавить(элемент,'класс_по_учебной_схеме','Средство обработки ПДн ошибочно отнесено к ВТСС','Проверить классификацию как ОТСС')
    for система in системы:
        for ссылка in система.get('связанное_оборудование',[]):
            элемент = next((о for о in оборудование if о['номер']==ссылка),None)
            if ссылка not in известные or система['номер'] not in элемент.get('связанная_испдн',[]):
                добавить({'номер':ссылка,'связанная_испдн':[система['номер']]},'обратная_ссылка','Оборудование отсутствует или обратная связь не согласована','Исправить ссылку в реестре и инвентаризации')
    return замечания
