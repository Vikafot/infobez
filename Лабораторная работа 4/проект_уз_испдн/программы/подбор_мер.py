def проверить_гис(система, организация=None):
    организация = организация or {}
    применимо = (система.get('является_гис') == 'да' or
                 организация.get('тип_организации') in ('государственная','муниципальная') or
                 система.get('получает_ограниченные_данные_гис') is True)
    return {'рассмотрено':True,'применимо':применимо,
       'приказ_17':'Историческое основание методички; утратил силу с 01.03.2026 согласно пп.2,4 приказа №117.',
       'действующее_основание':'Приказ ФСТЭК от 11.04.2025 №117; проверять действующую редакцию на дату применения.',
       'обоснование':('Нужна отдельная классификация К1–К3 и проверка требований №117; УЗ не заменяет класс.' if применимо else
                      'Частная ИСПДн коммерческого оператора, не ГИС; данных ограниченного доступа из ГИС нет.'),
       'статус':'недостаточно_данных' if применимо else 'соответствует'}

def подобрать_меры(система, уровень, каталог_мер):
    значение = уровень.get('уровень') if isinstance(уровень, dict) else уровень
    результат = {'требуемые':[],'фактически_реализованные':list(система.get('фактические_меры',[])),
                 'пробелы':[],'неприменимые':[],'ошибки':[]}
    if значение not in ('УЗ-1','УЗ-2','УЗ-3','УЗ-4'):
        результат['ошибки'].append('Нельзя подобрать меры: уровень не определён')
        return результат
    for мера in каталог_мер:
        условие = мера['условие_применения']
        включить = значение in мера['для_каких_уз'] and (условие == 'всегда' or система.get(условие) is True)
        запись = dict(мера)
        if включить:
            запись['причина_включения'] = f'Профиль {значение}; условие {условие} выполнено'
            запись['подтверждение'] = система.get('подтверждения_мер',{}).get(мера['код'],'')
            результат['требуемые'].append(запись)
            if мера['код'] not in результат['фактически_реализованные'] or not запись['подтверждение']:
                результат['пробелы'].append(запись)
        else:
            запись['обоснование_неприменимости'] = (f'Расширенный профиль для {значение} не включает эту меру.' if значение not in мера['для_каких_уз'] else
                система.get('обоснования_неприменимости',{}).get(мера['код'],''))
            результат['неприменимые'].append(запись)
    return результат
