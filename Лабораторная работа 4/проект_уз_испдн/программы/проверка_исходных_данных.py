from программы.расчёт_уз import уровень_системы

ПОЛЯ_ОРГАНИЗАЦИИ = ('название','отрасль','год_основания','город','число_сотрудников','число_субъектов_всех_систем',
 'ответственный_за_защиту_пдн','руководитель_проекта','тип_организации','есть_гис','основные_технологии',
 'внешние_интеграции','описание_инфраструктуры','особенности_обработки_пдн')
ПОЛЯ_СИСТЕМЫ = ('номер','название','назначение','границы_системы','категория_пдн','примеры_данных','тип_субъектов',
 'количество_субъектов','тип_угроз_по_условию','является_гис','фактические_меры','заявленный_уз','связанное_оборудование','ответственный')

def проверить_вход(организация, системы, оборудование, каталог, средства):
    ошибки=[]
    def ошибка(файл, поле, текст):
        ошибки.append({'файл':файл,'поле':поле,'причина':текст})
    if not isinstance(организация,dict):
        ошибка('данные/организация.py','организация','Ожидался словарь')
        return ошибки
    if not isinstance(системы,list) or not системы:
        ошибка('данные/системы.py','системы','Ожидался непустой список')
        return ошибки
    for поле in ПОЛЯ_ОРГАНИЗАЦИИ:
        if поле not in организация or организация[поле] is None or организация[поле]=='':
            ошибка('данные/организация.py',поле,'Обязательное поле не заполнено')
    for поле in ('число_сотрудников','число_субъектов_всех_систем','год_основания'):
        if type(организация.get(поле)) is not int or организация[поле]<1:
            ошибка('данные/организация.py',поле,'Нужно положительное целое число')
    if type(организация.get('есть_гис')) is not bool:
        ошибка('данные/организация.py','есть_гис','Нужно логическое значение')
    if организация.get('тип_организации') not in ('коммерческая','государственная','муниципальная'):
        ошибка('данные/организация.py','тип_организации','Недопустимое значение')
    номера=[]
    коды={м['код'] for м in каталог}
    for с in системы:
        if not isinstance(с,dict):
            ошибка('данные/системы.py','запись','Нужен словарь'); continue
        номер=с.get('номер','?');номера.append(номер)
        for поле in ПОЛЯ_СИСТЕМЫ:
            if поле not in с or (с[поле] in ('',None) and поле!='заявленный_уз'):
                ошибка('данные/системы.py',f'{номер}.{поле}','Поле отсутствует или пустое')
        for текст in уровень_системы(с)['ошибки_ввода']:
            ошибка('данные/системы.py',номер,текст)
        if с.get('является_гис') not in ('да','нет'):
            ошибка('данные/системы.py',f'{номер}.является_гис','Нужно да или нет')
        for поле in ('примеры_данных','фактические_меры','связанное_оборудование'):
            if not isinstance(с.get(поле),list):
                ошибка('данные/системы.py',f'{номер}.{поле}','Нужен список')
        if isinstance(с.get('фактические_меры'),list) and any(к not in коды for к in с['фактические_меры']):
            ошибка('данные/системы.py',f'{номер}.фактические_меры','Неизвестный код меры')
        if с.get('заявленный_уз') not in (None,'','УЗ-1','УЗ-2','УЗ-3','УЗ-4'):
            ошибка('данные/системы.py',f'{номер}.заявленный_уз','Недопустимый уровень')
    if len(номера)!=len(set(номера)):
        ошибка('данные/системы.py','номер','Повторяются идентификаторы')
    for имя, список in (('оборудование',оборудование),('справочник_сзи',средства)):
        if not isinstance(список,list) or not all(isinstance(з,dict) for з in список):
            ошибка('данные/'+имя+'.py',имя,'Нужен список словарей')
    return ошибки

