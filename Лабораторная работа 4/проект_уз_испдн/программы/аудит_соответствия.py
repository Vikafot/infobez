from программы.проверка_исходных_данных import проверить_вход, согласовать_численность
from программы.проверка_оборудования import проверить_оборудование
from программы.подбор_мер import проверить_гис
from программы.расчёт_уз import рассчитать_уз

def аудит(организация, системы, оборудование, средства, каталог, расчёты, меры, документы):
    строки=[]
    def пункт(код, имя, статус, факт, причина='', рекомендация='Контроль выполнен; сохранять подтверждения'):
        строки.append(dict(код=код, проверка=имя, статус=статус, факт=факт, причина=причина or 'Проверено общим правилом', рекомендация=рекомендация))
    ошибки=проверить_вход(организация,системы,оборудование,каталог,средства)
    пункт('А01','Полнота паспорта и реестра','несоответствие' if ошибки else 'соответствует',str(ошибки or 'Все обязательные поля заполнены'))
    входы=[с['номер'] for с in системы if расчёты[с['номер']]['ошибки_ввода']]
    пункт('А02','Допустимость параметров','несоответствие' if входы else 'соответствует',str(входы or 'Категории, группы, числа и типы угроз допустимы'))
    численность=согласовать_численность(организация,системы)
    пункт('А03','Численность и признак ГИС','соответствует' if численность['соответствует'] else 'несоответствие',численность['факт'],рекомендация='Учитывать пересечения субъектов и согласовать паспорт с реестром')
    for с in системы:
        номер=с['номер']; расчёт=расчёты[номер]; набор=меры[номер]
        прежний=с.get('заявленный_уз')
        пункт('А04/'+номер,'Заявленный и рассчитанный УЗ','несоответствие' if прежний and прежний!=расчёт['уровень'] else 'соответствует',
              f'{номер}: заявлено {прежний}, рассчитано {расчёт["уровень"]}',рекомендация='Сверить параметры и переутвердить акт при расхождении')
        пробелы=[м['код'] for м in набор['пробелы']]
        пункт('А08/'+номер,'Полнота реализованных мер','несоответствие' if пробелы else 'соответствует',
              f'{номер}: отсутствуют или не подтверждены {пробелы}',рекомендация='Реализовать отсутствующие меры и провести функциональные испытания')
        гис=проверить_гис(с,организация)
        пункт('А10/'+номер,'Применимость №17 и актуальных требований ГИС',гис['статус'],гис['приказ_17']+' '+гис['обоснование'],рекомендация='При применимости выполнить отдельную проверку №117 и классификацию К1–К3')
        без_основания=[м['код'] for м in набор['неприменимые'] if not м['обоснование_неприменимости']]
        пункт('А11/'+номер,'Обоснования неприменимости','несоответствие' if без_основания else 'соответствует',str(без_основания or f'{номер}: обоснования сохранены'))
    пороги=[рассчитать_уз('иные','не_сотрудники',к,2)['уровень'] for к in (99999,100000,100001)]
    пункт('А05','Граница 100000','соответствует' if пороги==['УЗ-3','УЗ-3','УЗ-2'] else 'несоответствие',
          str(пороги)+'; явное учебное допущение ≤100000; юридическая неоднозначность описана в отчёте')
    проблемы=проверить_оборудование(оборудование,системы)
    for код,имя,поля in [('А06','Ссылки оборудования',('связанная_испдн','обратная_ссылка')),
                         ('А07','Классификация ОТСС/ВТСС',('класс_по_учебной_схеме',)),
                         ('А13','Согласованность роли оборудования',('обрабатывает_пдн',))]:
        найдено=[п for п in проблемы if п['поле'] in поля]
        пункт(код,имя,'несоответствие' if найдено else 'соответствует',str(найдено or 'Ошибок не выявлено'),рекомендация='Уточнить инвентаризацию, роль и связи элементов')
    неполные=[с['название'] for с in средства if not с.get('источник_сведений') or not с.get('сертификат_или_статус') or
        с.get('тип_средства') not in ('СЗИ','СКЗИ') or not set(с.get('связанная_система',[])) <= {и['номер'] for и in системы} or
        (с.get('класс_сзи') and с.get('класс_скзи'))]
    непроверенные=[с['название'] for с in средства if not с.get('проверен_статус')]
    пункт('А09','Сведения о СЗИ/СКЗИ','несоответствие' if неполные else ('замечание' if непроверенные else 'соответствует'),
          f'Неполные записи: {неполные}; учебные/непроверенные статусы: {непроверенные}',
          'Шкалы классов разделены. Наличие описания макета не подтверждает сертификацию.',
          'До внедрения подобрать реальные средства и проверить сертификаты, версии и условия применения по реестрам ФСТЭК/ФСБ')
    отсутствуют=[имя for имя in ('акты','план','дата') if not документы.get(имя)]
    пункт('А12','Наличие актов, плана и даты','несоответствие' if отсутствуют else 'соответствует',str(отсутствуют or документы))
    веса={'соответствует':1,'замечание':0.5,'несоответствие':0,'недостаточно_данных':0}
    балл=round(100*sum(веса[с['статус']] for с in строки)/len(строки),1)
    return {'проверки':строки,'оценка':балл,'проблемы_оборудования':проблемы,
            'дефекты':[с for с in строки if с['статус']=='несоответствие']}
