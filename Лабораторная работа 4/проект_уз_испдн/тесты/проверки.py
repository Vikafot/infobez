def проверить_состояние(системы_для_теста,оборудование_для_теста):
    расчёты={с['номер']:уровень_системы(с) for с in системы_для_теста}
    меры={с['номер']:подобрать_меры(с,расчёты[с['номер']],каталог_мер) for с in системы_для_теста}
    return аудит(организация,системы_для_теста,оборудование_для_теста,средства,каталог_мер,расчёты,меры,{'акты':True,'план':True,'дата':'01.11.2026'})

def выполнить_тесты():
    результаты=[]
    def тест(название,вход,ожидание,факт):
        результаты.append({'номер':len(результаты)+1,'тест':название,'вход':вход,
                           'ожидаемый':ожидание,'фактический':факт,'пройден':ожидание==факт})
    # Независимые ожидаемые тройки фиксируют известные результаты, а не читают матрицу.
    эталоны=[('специальные','не_сотрудники',15000,['УЗ-1','УЗ-2','УЗ-3']),
      ('специальные','не_сотрудники',120000,['УЗ-1','УЗ-1','УЗ-2']),
      ('биометрические','сотрудники',6000,['УЗ-1','УЗ-2','УЗ-3']),
      ('общедоступные','не_сотрудники',85000,['УЗ-2','УЗ-3','УЗ-4']),
      ('общедоступные','не_сотрудники',120000,['УЗ-2','УЗ-2','УЗ-4']),
      ('иные','сотрудники',700,['УЗ-1','УЗ-3','УЗ-4']),
      ('иные','не_сотрудники',160000,['УЗ-1','УЗ-2','УЗ-3'])]
    for категория,группа,число,уровни in эталоны:
        for угроза,ожидание in enumerate(уровни,1):
            вход=[категория,группа,число,угроза]
            тест('Расчёт категории и типа угроз',вход,ожидание,рассчитать_уз(*вход)['уровень'])
    for число,ожидание in [(99999,'УЗ-3'),(100000,'УЗ-3'),(100001,'УЗ-2')]:
        вход=['иные','не_сотрудники',число,2]
        тест('Порог',вход,ожидание,рассчитать_уз(*вход)['уровень'])
    for вход in [[None,'сотрудники',10,3],['','сотрудники',10,3],['неизвестная','сотрудники',10,3],
                 ['иные','посетители',10,3],['иные','сотрудники',-1,3],['иные','сотрудники',0,3],
                 ['иные','сотрудники',True,3],['иные','сотрудники',1.5,3],['иные','сотрудники',None,3],
                 ['иные','сотрудники',10,4],['иные','сотрудники',10,True],['иные','сотрудники',10,None],
                 [[], 'сотрудники',10,3]]:
        тест('Недопустимый или отсутствующий параметр',вход,'недостаточно_данных',рассчитать_уз(*вход)['уровень'])
    для_пробела=копия(исходные_системы[1]);для_пробела['фактические_меры'].remove('ОДТ.5')
    пробелы=подобрать_меры(для_пробела,уровень_системы(для_пробела),каталог_мер)['пробелы']
    тест('Пропущенная мера','удалена ОДТ.5',['ОДТ.5'],[м['код'] for м in пробелы])
    неверные=копия(исходные_системы);неверные[0]['связанное_оборудование'].append('НЕСУЩЕСТВУЕТ')
    найдено=проверить_оборудование(исходное_оборудование,неверные)
    тест('Несуществующая ссылка на оборудование','связь НЕСУЩЕСТВУЕТ',True,any(п['оборудование']=='НЕСУЩЕСТВУЕТ' for п in найдено))
    неверные=копия(исходное_оборудование);неверные[0]['связанная_испдн']=['НЕИЗВЕСТНАЯ']
    тест('Ссылка оборудования на неизвестную систему','НЕИЗВЕСТНАЯ',True,
         any(п['поле']=='связанная_испдн' for п in проверить_оборудование(неверные,исходные_системы)))
    неверные=копия(исходное_оборудование);неверные[0]['обрабатывает_пдн']=False
    тест('Противоречие роли','БД: обрабатывает_пдн=False',True,
         any(п['поле']=='обрабатывает_пдн' for п in проверить_оборудование(неверные,исходные_системы)))
    гис=копия(исходные_системы[0]);гис['является_гис']='да'
    тест('Признак ГИС требует отдельного анализа',{'является_гис':'да'},'недостаточно_данных',проверить_гис(гис,организация)['статус'])
    тест('Обычная коммерческая ИСПДн',{'является_гис':'нет'},False,проверить_гис(исходные_системы[0],организация)['применимо'])
    гис=копия(исходные_системы[0]);гис['получает_ограниченные_данные_гис']=True
    тест('Интеграция с ГИС','получает ограниченные данные',True,проверить_гис(гис,организация)['применимо'])
    набор=подобрать_меры(исходные_системы[2],уровень_системы(исходные_системы[2]),каталог_мер)
    тест('Обоснование неприменимости ЗСВ','МД: физический сервер',True,
         any(м['код']=='ЗСВ.1' and bool(м['обоснование_неприменимости']) for м in набор['неприменимые']))
    тест('Подсчёт уникальных субъектов','120+120000+15000−15000',True,согласовать_численность(организация,исходные_системы)['соответствует'])
    базовый=проверить_состояние(исходные_системы,исходное_оборудование)
    дефектный=проверить_состояние(системы,оборудование)
    тест('Исходное состояние без трёх дефектов','снимки до внесения',0,len(базовый['дефекты']))
    тест('Три дефекта обнаружены','рабочие данные',3,len(дефектный['дефекты']))
    # Переименование идентификаторов подтверждает отсутствие поиска заданных номеров.
    новые_системы=копия(системы);новое_оборудование=копия(оборудование)
    соответствие={с['номер']:'НОВЫЙ'+str(н) for н,с in enumerate(новые_системы)}
    for с in новые_системы: с['номер']=соответствие[с['номер']]
    for о in новое_оборудование: о['связанная_испдн']=[соответствие[н] for н in о['связанная_испдн']]
    from данные.организация import организация as исходная_организация
    # Здесь сравниваются именно три контрольных типа, независимо от численности и связей средств.
    расчёты={с['номер']:уровень_системы(с) for с in новые_системы}
    меры={с['номер']:подобрать_меры(с,расчёты[с['номер']],каталог_мер) for с in новые_системы}
    орг=копия(организация)
    for п in орг['пересечения']: п['системы']=[соответствие[н] for н in п['системы']]
    сзи=копия(средства)
    for с in сзи: с['связанная_система']=[соответствие[н] for н in с['связанная_система']]
    переименованный=аудит(орг,новые_системы,новое_оборудование,сзи,каталог_мер,расчёты,меры,{'акты':True,'план':True,'дата':'01.11.2026'})
    тест('Аудит не зависит от номеров','все идентификаторы заменены',3,len(переименованный['дефекты']))
    for сценарий in сценарии:
        факт=[рассчитать_уз(*в)['уровень'] for в in сценарий['входы']]
        тест('Сценарий '+str(сценарий['номер']),сценарий['входы'],сценарий['ожидается'],факт)
    тест('Смешанный контур: более строгий уровень',['УЗ-4','УЗ-2'],'УЗ-2',строгий_уровень([{'уровень':'УЗ-4'},{'уровень':'УЗ-2'}]))
    тест('Неполный смешанный контур',['УЗ-2','недостаточно_данных'],'недостаточно_данных',строгий_уровень([{'уровень':'УЗ-2'},{'уровень':'недостаточно_данных'}]))
    from программы.главный_симулятор import безопасно, загрузить, импорт_акта, КОРЕНЬ
    тест('Команда без номера','система',True,безопасно('система').startswith('Ошибка:'))
    тест('Импорт без номера','сценарий импорт',True,безопасно('сценарий импорт').startswith('Ошибка:'))
    тест('Формирование DOCX акта','сценарий импорт КД',True,безопасно('сценарий импорт КД').startswith('Акт сформирован:'))
    исходник=копия(исходные_системы);исходник[0]['тип_угроз_по_условию']=4
    тест('Валидация с адресом поля','КД: тип угроз 4',True,
         any(о['файл']=='данные/системы.py' and 'тип_угроз' in о['причина'] for о in проверить_вход(организация,исходник,исходное_оборудование,каталог_мер,средства)))
    текст=['АВТОМАТИЧЕСКИЕ ТЕСТЫ','№ | Проверка | Вход | Ожидаемый результат | Фактический результат | Пройден']
    текст.extend(' | '.join(str(р[к]) for к in ('номер','тест','вход','ожидаемый','фактический','пройден')) for р in результаты)
    (КОРЕНЬ/'отчёты/автоматические_тесты.txt').write_text('\n'.join(текст)+'\n',encoding='utf-8')
    (КОРЕНЬ/'отчёты/автоматические_тесты.json').write_text(обмен.dumps(результаты,ensure_ascii=False,indent=2),encoding='utf-8')
    (КОРЕНЬ/'отчёты/сравнение_состояний.txt').write_text(
      f'До внесения: дефектов {len(базовый["дефекты"])}, балл {базовый["оценка"]}.\nПосле внесения: дефектов {len(дефектный["дефекты"])}, балл {дефектный["оценка"]}.\n'
      'После исправления трёх дефектов в копии данных: '+str(базовый['оценка'])+'/100. Реальная инфраструктура не изменялась.\n'
      'Остаётся замечание о неподтверждённых учебных СЗИ/СКЗИ; расчёт относится только к учебной модели.\n'
      'Ожидалось: ошибка заявленного уровня, отсутствующая ОДТ.5 и пустой класс принтера.\n'
      'Фактически: '+обмен.dumps(дефектный['дефекты'],ensure_ascii=False,indent=2),encoding='utf-8')
    return результаты
